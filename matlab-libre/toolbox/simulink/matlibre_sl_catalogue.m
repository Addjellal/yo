% --- les recherches ---------------------------------------------------------

function index = indexer(cat)
    index = containers.Map();
    for k = 1:numel(cat)
        cles = [{cat(k).type, cat(k).simulink, cat(k).affiche}, cat(k).chemins, ...
                cat(k).aliasTypes];
        for j = 1:numel(cles)
            cle = normaliser(cles{j});
            if ~isKey(index, cle)
                index(cle) = k;
            end
        end
    end
end

% Une désignation se compare sans la casse ni les espaces : « Sine Wave »,
% « sinewave » et « SineWave » désignent le même bloc.
function cle = normaliser(texte)
    cle = lower(regexprep(char(texte), '\s', ''));
end

function x = resoudreType(cat, index, designation)
    if isstruct(designation)
        x = designation;
        return
    end
    brut = char(designation);
    cle = normaliser(brut);
    if isKey(index, cle)
        x = cat(index(cle));
        return
    end
    % Un chemin de bibliothèque qu'on ne connaît pas en entier : son
    % dernier segment est le nom du bloc.
    barre = find(brut == '/', 1, 'last');
    if ~isempty(barre)
        dernier = normaliser(brut(barre + 1:end));
        if isKey(index, dernier)
            x = cat(index(dernier));
            return
        end
    end
    error('Simulink:Commands:InvalidBlockType', ...
          ['Le type de bloc ''%s'' est inconnu. Les types reconnus sont ceux ' ...
           'qu''ADD_BLOCK decrit ; ils se designent aussi par leur nom Simulink ' ...
           '(''Gain'', ''Sine Wave'') ou leur chemin de bibliotheque ' ...
           '(''simulink/Math Operations/Gain'').'], brut);
end

function nom = resoudreParametre(x, demande)
    nom = '';
    demande = char(demande);
    for k = 1:size(x.params, 1)
        if strcmpi(x.params{k, 1}, demande)
            nom = x.params{k, 1};
            return
        end
    end
    for k = 1:size(x.alias, 1)
        if strcmpi(x.alias{k, 1}, demande)
            nom = x.alias{k, 2};
            return
        end
    end
    communs = parametresCommuns();
    for k = 1:numel(communs)
        if strcmpi(communs{k}, demande)
            nom = communs{k};
            return
        end
    end
end
